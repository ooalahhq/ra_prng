#!/usr/bin/env python3
"""Render the current audited JSON datasets into RESULTS.md without typed-in KPIs."""

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
DATA = HERE / "data"


def read(name):
    return json.loads((DATA / name).read_text())


def table(headers, rows):
    lines = ["| " + " | ".join(headers) + " |", "| " + " | ".join(["---"] * len(headers)) + " |"]
    lines += ["| " + " | ".join(map(str, row)) + " |" for row in rows]
    return "\n".join(lines)


def metric(row, regime, field="mibs"):
    value = row["regimes"].get(regime)
    return "—" if value is None else f"{value[field]:,.1f}"


def main():
    micro = read("shootout_microbench.json")
    mc = read("mc_workloads_v2.json")
    manifest = read("fairness_manifest.json")
    summary = read("shootout_sample_summary.json")
    lines = [
        "# Fairness-audited PRNG shootout — ra_core v2",
        "",
        "This report is generated from `data/*.json` by `render_fairness_results.py`. The original narrative is retained as `RESULTS_PRE_AUDIT.md` and is superseded for performance claims.",
        "",
        "## Measurement contract",
        "",
        "- Compiler: `" + " ".join(manifest["programs"]["micro"]["compile_command"]) + "`; core `" + str(manifest["core"]) + "`; " + manifest["compiler"] + ".",
        "- Suite A/B/D: scalar or sequential paths with compiler auto-vectorization disabled. Suite C: eight independent streams using explicit AVX2 intrinsics. These are separate regimes.",
        "- Suite A inlined stream counts native output width: 8 bytes for xoshiro256**, xoroshiro128++, SplitMix64 and WyRand; 4 bytes for the other rows. `ns/64b` and `cpb` use actual generated bytes.",
        "- Microbenchmark: one warmup plus seven measured rounds, minimum for headline throughput and median retained in `data/shootout_sample_summary.json`. Raw seconds, cycles and byte counts are in `data/shootout_samples.csv`.",
        "- Monte Carlo timings include the consumer in each named regime. Five raw seconds per timing row are saved in the individual workload JSON and checked against the reported minimum and median. A speed comparison across regimes is not an RNG-only speedup. Different PRNG families use different streams and can take different random branches.",
        "- This is *shootout-inspired*, not an exact reproduction of Vigna's harness or its loop-unrolling policy.",
        "",
        "## Suite A — inlined and buffer endpoints",
        "",
        "Four families return native 64-bit values in the continuous inlined stream; the per-seed K=1 and materialized buffer APIs return 32-bit words. Compare each endpoint on its own terms: actual bytes are counted, but the call and output-width contracts differ.",
        "",
        table(["Generator", "Stream inlined MiB/s", "Stream inlined cpb", "Stream buffer MiB/s", "K=1 inlined MiB/s", "K=1 buffer MiB/s"], [
            [r["name"], f"{r['inlined_stream']['mibs']:,.1f}", f"{r['inlined_stream']['cpb']:.3f}", f"{r['buffer_stream']['mibs']:,.1f}", f"{r['inlined_k1']['mibs']:,.1f}", f"{r['buffer_k1']['mibs']:,.1f}"]
            for r in micro["suite_a_vigna_shootout"]
        ]),
        "",
        "## Suite B — scalar direct buffer",
        "",
        "MiB/s of generated 32-bit words. `stream` is a long single-buffer call; short bursts include per-seed setup.",
        "",
        table(["Generator", "K=1", "K=8", "K=255", "stream"], [
            [r["name"], *(metric(r, k) for k in ("K=1", "K=8", "K=255", "stream"))]
            for r in micro["suite_b_scalar_buffer"]["generators"]
        ]),
        "",
        "## Suite C — eight-way AVX2",
        "",
        "MiB/s of eight distinct stream lanes. A missing implementation or invalid `K>N-1` is N/A, not zero throughput.",
        "",
        table(["Generator", "K=1", "K=15", "K=255"], [
            [r["name"], *(metric(r, k) for k in ("K=1", "K=15", "K=255"))]
            for r in micro["suite_c_avx2_x8"]["generators"]
        ]),
        "",
        "## Suite D — stateful init + next",
        "",
        "MiB/s includes one initialization per burst and one `next_u32()` call per output.",
        "",
        table(["Generator", "K=1", "K=8", "K=255", "K=1000"], [
            [r["name"], *(metric(r, k) for k in ("K=1", "K=8", "K=255", "K=1000"))]
            for r in micro["suite_d_stateful_engine"]["engines"]
        ]),
        "",
        "## Workload 1 — photon transport and rare trigger",
        "",
        "Natural stochastic trajectories differ across generator families. The table reports observed work so runtime is not read as pure RNG cost. OTF/eager parity applies within each RA version.",
        "",
    ]
    photon = mc["workload1"]["photon_transport"]
    rare = {r["name"].split(" (")[0]: r for r in mc["workload1"]["rare_event_trigger"]}
    p_rows = []
    for r in photon[0]["generators"]:
        name = r["name"]
        matches = [next((x for x in group["generators"] if x["name"] == name), None) for group in photon]
        rare_row = rare.get(name.split(" (")[0])
        p_rows.append([name, *("—" if x is None else f"{x['wall_min']:.4f}/{x['total_words']:,}" for x in matches),
                       "—" if rare_row is None else f"{rare_row['wall_min']:.4f}/{rare_row['total_words']:,}"])
    lines += [table(["Generator", "P=.50 s/words", "P=.80 s/words", "P=.90 s/words", "P=.98 s/words"], p_rows), ""]

    pi = mc["workload2"]
    lines += [
        "## Workload 2 — bounded-burst π",
        "",
        "Scalar and AVX2 consumers both map the upper 24 bits to midpoint `float` coordinates. Each odd-`K` burst generates one final unused word; MiB/s counts generated bytes, while the JSON records generated and consumed words separately. The exact scalar/AVX2 inside-count parity gate must pass before release.",
        "",
        table(["Generator, AVX2 K=255", "Inside", "Generated words", "Consumed words", "min s", "generated MiB/s"], [
            [r["name"], f"{r['inside']:,}", f"{r['generated_words']:,.0f}", f"{r['consumed_words']:,.0f}", f"{r['wall_min']:.4f}", f"{r['mibs']:,.1f}"]
            for r in pi["avx2_consumer_k255"]
        ]),
        "",
        "### Eight-lane Bernoulli flip diagnostic",
        "",
        "This consumer compares generated words with a fixed threshold and counts flips. It does not simulate an Ising lattice or Metropolis transitions.",
        "",
        table(["Generator, K=255", "Flips", "min s", "generated MiB/s"], [
            [r["name"], f"{r['flips']:,}", f"{r['wall_min']:.4f}", f"{r['mibs']:,.1f}"]
            for r in pi["bernoulli_flip_avx2_k255"]
        ]),
        "",
        "## Workload 3 — Asian option GBM",
        "",
        "Pure generation and end-to-end pricing are separate metrics. Families use their documented native path/seed mapping; option payoffs are statistical estimates, not bit-exact across families. The Philox key-only row is a diagnostic control.",
        "",
        table(["Generator", "Payoff ± SE", "Pure gen min s", "Gen MiB/s", "End-to-end min s"], [
            [r["name"], f"{r['mean_payoff']:.4f} ± {r['se']:.4f}", f"{r['gen_min']:.4f}", f"{r['gen_mibs']:,.1f}", f"{r['e2e_min']:.4f}"]
            for r in mc["workload3"]["asian_option_gbm"]
        ]),
        "",
        "## Branching tree — scheduler invariance within RA",
        "",
        "These measurements come from the separate Group 3 experiment. RA schedules share a node/output hash. Philox uses a different random tree (different node and draw counts), so **cross-family speed ratios are withheld** until a fixed-trace same-work rerun exists.",
        "",
    ]
    tree = mc["group3_branching_tree"]
    lines += [table(["RA schedule", "Nodes", "Mismatches vs S1", "Time ms"], [
        [name, f"{r['total_nodes']:,}", r["mismatches_vs_S1"], f"{r['time_ms']:.3f}"]
        for name, r in tree["schedules"].items()
    ]), "", f"Philox reference observed {tree['baseline_comparisons']['Philox4x32_10_total_nodes']:,} nodes and {tree['baseline_comparisons']['Philox4x32_10_total_words']:,} draws; RA observed {tree['total_nodes_evaluated']:,} nodes and {tree['total_words_drawn']:,} draws.", ""]
    short = [r for r in summary if r["short_sample_under_5ms"]]
    spread = [r for r in summary if r["median_s"] / r["min_s"] > 1.10]
    lines += [
        "## Audit outcome and limitations",
        "",
        f"- Micro raw sample accounting: {len(summary)} measured regime rows, {len(summary) * 7} saved samples, {len(short)} rows with minimum sample under 5 ms.",
        f"- {len(spread)} micro rows have a median time more than 10% above their minimum. Use the saved medians when a small difference would change a ranking; minimum-only rankings are sensitive to runtime variation.",
        f"- Monte Carlo raw timing accounting: {manifest['mc_audit']['timing_rows_checked']} timing rows and {manifest['mc_audit']['raw_timing_samples']} saved samples passed minimum/median reconciliation.",
        "- Source, binary and output hashes, build commands, CPU and affinity: `data/fairness_manifest.json`.",
        "- Original performance narrative: `RESULTS_PRE_AUDIT.md` (historical, superseded). Statistical quality and feature claims in `data/shootout_feature_matrix.json` are manually curated from earlier experiments and references; this speed rerun does not independently establish them.",
        "- Figures and dashboard are generated from the same JSON inputs. Numeric headlines in the dashboard are computed from data at render time.",
        "",
    ]
    (HERE / "RESULTS.md").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
